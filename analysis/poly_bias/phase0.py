"""Phase 0 diagnosis: is the bot a Polymarket-convergence bettor?
Usage: python analysis/poly_bias/phase0.py DATA_DIR   (DATA_DIR holds market_data.sql, status.json, fills.csv
extracted from ops-snapshot-2026-10-02 with `git show BRANCH:path > file`; data never enters this branch).
Method: per-market position history from snapshots(position) (live rows). A change in position between two
snapshots is a trade, priced at the tournament mid of the later snapshot (fills.csv has 46% unknown sides, so
it is used only as a turnover cross-check). Lots are FIFO. Capital = qty*mid for longs, qty*(1-mid) for shorts.
"""
import sys, sqlite3, json, csv, statistics as st, collections, datetime as dt
D = sys.argv[1]
db = sqlite3.connect(":memory:"); db.executescript(open(f"{D}/market_data.sql").read())
rows = db.execute("select ts,eid,label,best_bid,best_ask,fair_value,reference,position from snapshots "
                  "where mode='live' order by ts").fetchall()
T = lambda s: dt.datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()
by = collections.defaultdict(list)
for r in rows: by[r[1]].append(r)
GAP_MIN = 0.005   # under half a cent the sign of the gap is noise: counted "neutral"
lots = collections.defaultdict(list)     # eid -> [qty_signed, ts, entry_mid, gap_at_entry(ref-mid), ]
ent = ext = 0.0; ent_cap = ext_cap = 0.0; realised = 0.0; hold_closed = []
ent_toward = ent_against = ent_neutral = ent_noref = 0.0
last = {}
for eid, rs in by.items():
    pos = 0.0; prev = None
    for r in rs:
        ts, _, label, bb, ba, fv, ref, p = r
        p = p or 0.0
        if bb is None or ba is None: prev = r; continue
        mid = (bb + ba) / 2; last[eid] = r
        d = p - pos
        if abs(d) > 1e-9:
            t = T(ts)
            # gap seen when the trade was decided: previous snapshot if it has one, else this one
            g = None
            for s in (prev, r):
                if s and s[6] is not None and s[3] is not None and s[4] is not None:
                    g = s[6] - (s[3] + s[4]) / 2; break
            L = lots[eid]
            # exits first (FIFO against opposite-signed... same-signed lots being reduced)
            while abs(d) > 1e-9 and L and L[0][0] * d < 0:
                q = min(abs(d), abs(L[0][0])); sg = 1 if L[0][0] > 0 else -1
                realised += sg * q * (mid - L[0][2]); ext += q
                ext_cap += q * (L[0][2] if sg > 0 else 1 - L[0][2])
                hold_closed.append((t - L[0][1], q))
                L[0][0] -= sg * q; d += sg * q
                if abs(L[0][0]) < 1e-9: L.pop(0)
            if abs(d) > 1e-9:
                cap = abs(d) * (mid if d > 0 else 1 - mid); ent += abs(d); ent_cap += cap
                if g is None: ent_noref += cap; tw = None
                elif abs(g) < GAP_MIN: ent_neutral += cap; tw = 0
                elif g * d > 0: ent_toward += cap; tw = 1
                else: ent_against += cap; tw = -1
                L.append([d, t, mid, g, tw])
            pos = p
        prev = r
now = max(T(r[0]) for r in last.values())
# ---- open book
open_rows = []; unreal = 0.0; hair = 0.0; polyval = 0.0; cap_tot = 0.0
age_cap = collections.Counter(); ages = []
tw_cap = collections.Counter()
for eid, L in lots.items():
    if not L: continue
    ts, _, label, bb, ba, fv, ref, p = last[eid]; mid = (bb + ba) / 2
    q = sum(l[0] for l in L); sg = 1 if q > 0 else -1
    cap = abs(q) * (mid if sg > 0 else 1 - mid); cap_tot += cap
    u = sum(l[0] * (mid - l[2]) for l in L); unreal += u
    h = abs(q) * ((mid - bb) if sg > 0 else (ba - mid)); hair += h
    pv = q * (ref - mid) if ref is not None else 0.0; polyval += pv
    capw = {1: 0.0, 0: 0.0, -1: 0.0, None: 0.0}
    for l in L:
        c = abs(l[0]) * (mid if sg > 0 else 1 - mid); capw[l[4]] += c; tw_cap[l[4]] += c
        a = (now - l[1]) / 3600; ages.append((a, c))
        age_cap[">6h"] += c * (a > 6); age_cap[">24h"] += c * (a > 24); age_cap[">12h"] += c * (a > 12)
    eg = sum(abs(l[0]) * l[3] for l in L if l[3] is not None) / max(1e-9, sum(abs(l[0]) for l in L if l[3] is not None))
    open_rows.append(dict(label=label, pos=q, cap=cap, mid=mid, ref=ref, gap_now=(ref - mid) if ref is not None else None,
                          gap_entry=eg, toward=capw[1] / cap if cap else 0, unreal=u, hair=h, polyval=pv,
                          age=sum(abs(l[0]) * (now - l[1]) / 3600 for l in L) / abs(q)))
open_rows.sort(key=lambda r: -r["cap"])
def wmedian(pairs):
    pairs = sorted(pairs); tot = sum(w for _, w in pairs); acc = 0
    for v, w in pairs:
        acc += w
        if acc >= tot / 2: return v
